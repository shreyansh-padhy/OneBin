-- 1. Create the scans telemetry table
create table if not exists public.scans (
  id bigint generated by default as identity primary key,
  bin text not null,
  item text not null,
  confidence numeric,
  image_url text,
  ms integer,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- Index for fast ordering and filtering
create index if not exists idx_scans_created_at on public.scans (created_at desc);
create index if not exists idx_scans_bin on public.scans (bin);

-- Enable Row Level Security (RLS)
alter table public.scans enable row level security;

-- Allow anonymous inserts (from bin kiosks and user feedback widget)
create policy "Allow anonymous inserts" on public.scans
  for insert to anon
  with check (true);

-- Allow anonymous reads (for live stage dashboard telemetry)
create policy "Allow anonymous reads" on public.scans
  for select to anon
  using (true);

-- Grant table & sequence permissions to anon role
grant usage on schema public to anon;
grant select, insert on public.scans to anon;
grant usage, select on all sequences in schema public to anon;

-- 2. Enable Realtime WebSocket broadcasts on scans table
alter publication supabase_realtime add table public.scans;

-- 3. Create the public storage bucket for user-consented dataset photos
insert into storage.buckets (id, name, public)
values ('waste-dataset', 'waste-dataset', true)
on conflict (id) do nothing;

-- 4. Storage upload & read security policies
create policy "Allow public uploads" on storage.objects 
  for insert to anon with check (bucket_id = 'waste-dataset');

create policy "Allow public reads" on storage.objects 
  for select to anon using (bucket_id = 'waste-dataset');

-- 5. Analytics RPC for instant diversion stats calculation
create or replace function get_bin_analytics()
returns json language plpgsql security definer as $$
declare
  total_count int;
  compost_count int;
  recycling_count int;
  trash_count int;
  diversion_pct numeric;
begin
  select count(*) into total_count from public.scans;
  select count(*) into compost_count from public.scans where bin = 'compost';
  select count(*) into recycling_count from public.scans where bin = 'recycling';
  select count(*) into trash_count from public.scans where bin = 'trash';
  
  if total_count > 0 then
    diversion_pct := round(((compost_count + recycling_count)::numeric / total_count::numeric) * 100, 1);
  else
    diversion_pct := 0;
  end if;

  return json_build_object(
    'total', total_count,
    'compost', compost_count,
    'recycling', recycling_count,
    'trash', trash_count,
    'diversion_rate', diversion_pct
  );
end;
$$;
